const { spawn } = require('child_process'); const { chromium } = require('playwright'); const fs=require('fs'),os=require('os'),path=require('path');
const DIR=__dirname, ROOT=path.join(DIR,'..'); const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const fake=spawn('python3',[path.join(DIR,'fake_nova.py'),path.join(ROOT,'cap/live4_conv.log'),path.join(DIR,'fake_rx10.txt'),'40','1']);
  const pty=await new Promise(r=>fake.stdout.once('data',d=>r(String(d).trim())));
  const data=fs.mkdtempSync(path.join(os.tmpdir(),'nr-'));
  const srv=spawn('node',[path.join(ROOT,'nova-remote/server.js'),'--port','8143','--no-open','--no-auto','--data',data]);
  await sleep(800); const b=await chromium.launch(); const p=await b.newPage({viewport:{width:1280,height:800}}); const errs=[]; p.on('pageerror',e=>errs.push(e.message));
  await p.goto('http://localhost:8143/'); await p.waitForFunction(()=>cart.ready);
  const count=async tag=>{ await p.evaluate(()=>go("inputs")); await sleep(200); const a=await p.evaluate(()=>[...document.querySelectorAll('.chlist .ch .n')].map(e=>e.textContent).join(','));
    await p.evaluate(()=>{ routeMode="tracks"; go("routing"); }); await sleep(200); const t=await p.evaluate(()=>document.querySelectorAll('.mx thead th[scope=col]').length);
    console.log(tag,'model=',await p.evaluate(()=>novaModel),'| inputs:',a,'| track cols',t,'| out1 sources',await p.evaluate(()=>outSources(0).length)); };
  await count('sim');
  await p.evaluate(path=>net.send({t:'serialOpen',path,baud:38400,parity:'odd'}),pty);
  await p.waitForFunction(()=>cart.nova&&cart.nova.connected,null,{timeout:15000}); await sleep(2500);
  await count('nova');
  await p.evaluate(()=>go("inputs")); await sleep(300); await p.screenshot({path:path.join(DIR,'nova1-inputs.png')});
  await p.reload(); await p.waitForFunction(()=>cart.ready); await sleep(500); await count('reload');
  console.log('link file', fs.readFileSync(path.join(data,'nova-link.json'),'utf8'), 'errors', errs);
  await b.close(); srv.kill(); fake.kill();
})().catch(e=>{console.error(e);process.exit(1)});
