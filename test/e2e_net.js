const { spawn, execSync } = require('child_process'); const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path');
const ROOT = path.join(__dirname, '..'); const sleep = ms => new Promise(r => setTimeout(r, ms));
const NOPROXY = { args: ['--no-proxy-server', '--proxy-bypass-list=*'], env: Object.fromEntries(Object.entries(process.env).filter(([k]) => !/proxy/i.test(k))) };
const IP = execSync('hostname -I').toString().trim().split(/\s+/)[0], PORT = 8142;
const probe = async host => { try { const r = await fetch(`http://${host}:${PORT}/api/help`, { signal: AbortSignal.timeout(1500) }); return r.status; } catch (e) { return 'refused'; } };
const startSrv = data => spawn('node', [path.join(ROOT, 'nova-remote/server.js'), '--port', String(PORT), '--no-open', '--local', '--data', data], { stdio: 'ignore' });
(async () => {
  const data = fs.mkdtempSync(path.join(__dirname, 'nrnet-')); let srv = startSrv(data); await sleep(900);
  console.log('start (off): local', await probe('127.0.0.1'), '| LAN', await probe(IP));
  const b = await chromium.launch(NOPROXY); const errs = [];
  const me = await b.newPage({ viewport: { width: 1280, height: 900 } }); me.on('pageerror', e => errs.push(e.message));
  await me.goto(`http://127.0.0.1:${PORT}/`); await me.waitForFunction(() => cart.ready);
  await me.evaluate(() => { setupSec = 'conn'; go('setup'); }); await sleep(400);
  console.log('switch shown', await me.isVisible('#f-network'), 'checked', await me.isChecked('#f-network'));
  console.log('hint:', (await me.locator('text=Off: only this computer').count()) > 0);
  await me.screenshot({ path: path.join(__dirname, 'net-off.png') });
  await me.check('#f-network'); await sleep(800);
  console.log('after on: LAN', await probe(IP), '| urls', JSON.stringify(await me.evaluate(() => cart.urls.map(u => u.url))));
  await me.screenshot({ path: path.join(__dirname, 'net-on.png') });
  const phone = await b.newPage({ viewport: { width: 390, height: 844 } }); phone.on('pageerror', e => errs.push(e.message));
  await phone.goto(`http://${IP}:${PORT}/`); await phone.waitForFunction(() => cart.ready);
  await phone.evaluate(() => { setupSec = 'conn'; go('setup'); }); await sleep(300);
  console.log('phone connected; its switch disabled:', await phone.isDisabled('#f-network'), '| devices', await me.evaluate(() => cart.devices));
  await phone.evaluate(() => net.send({ t: 'network', on: false })); await sleep(500);
  console.log('phone tried to switch off -> LAN still', await probe(IP));
  await me.uncheck('#f-network'); await sleep(1500);
  console.log('after off: LAN', await probe(IP), '| local', await probe('127.0.0.1'), '| desktop.json', fs.readFileSync(path.join(data, 'desktop.json'), 'utf8'));
  console.log('phone status pill:', await phone.evaluate(() => document.querySelector('[role=status]')?.textContent || ''));
  await me.check('#f-network'); await sleep(600); srv.kill(); await sleep(500);
  srv = startSrv(data); await sleep(900);
  console.log('restart remembers on: LAN', await probe(IP));
  srv.kill(); await b.close(); fs.rmSync(data, { recursive: true });
  // plain cart version: switch hidden
  const d2 = fs.mkdtempSync(path.join(__dirname, 'nrnet-'));
  const s2 = spawn('node', [path.join(ROOT, 'nova-remote/server.js'), '--port', String(PORT), '--no-open', '--data', d2], { stdio: 'ignore' }); await sleep(900);
  const b2 = await chromium.launch(NOPROXY); const p2 = await b2.newPage(); await p2.goto(`http://127.0.0.1:${PORT}/`); await p2.waitForFunction(() => cart.ready);
  await p2.evaluate(() => { setupSec = 'conn'; go('setup'); }); await sleep(300);
  console.log('cart version: switch visible', await p2.isVisible('#f-network'), '| LAN', await probe(IP));
  await b2.close(); s2.kill(); fs.rmSync(d2, { recursive: true });
  console.log('errors', errs);
})().catch(e => { console.error(e); process.exit(1); });
