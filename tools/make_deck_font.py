"""Nov 14: the bitmap font Nova Relay draws Stream Deck keys with on Linux / the Pi box (nova-remote/deck/font.js).

The Stream Deck plugin draws its keys as SVG text in "Helvetica Neue, Helvetica, Arial" bold; the Stream Deck app turns
that into pixels. On the Pi there's no Stream Deck app and no font library, so Nova Relay carries the glyphs itself:
Liberation Sans Bold (metric-compatible with Arial; SIL Open Font License 1.1), with DejaVu Sans Bold for the few
symbols Liberation lacks (Bitstream Vera / DejaVu license). Each glyph is an 8-bit coverage map at EM pixels per em.

  python3 tools/make_deck_font.py            (writes nova-remote/deck/font.js)
"""
import base64, json, os, sys, zlib
from PIL import ImageFont
from fontTools.ttLib import TTFont

EM = 64
MAIN = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
BACK = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT = os.path.join(os.path.dirname(__file__), "..", "nova-remote", "deck", "font.js")

chars = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(160, 256)]
chars += list("–—−‘’“”…•·←↑→↓▲▼▸◂▶◀●○■✓✕€™ŒœŠšŽžŸ")
chars = sorted(set(chars), key=ord)
SYMBOLS = set("\u2190\u2191\u2192\u2193\u25b2\u25bc\u25b8\u25c2\u25b6\u25c0\u25cf\u25cb\u25a0\u2713\u2715")

cmap_main = TTFont(MAIN).getBestCmap()
cmap_back = TTFont(BACK).getBestCmap()
f_main = ImageFont.truetype(MAIN, EM)
f_back = ImageFont.truetype(BACK, EM)

glyphs, blob = {}, bytearray()
asc, desc = f_main.getmetrics()
for ch in chars:
    prefer_back = ch in SYMBOLS and ord(ch) in cmap_back   # arrows and shapes: DejaVu's are fuller, as browsers draw them
    f = f_back if prefer_back else f_main if ord(ch) in cmap_main else f_back if ord(ch) in cmap_back else None
    if f is None:
        continue
    adv = f.getlength(ch)
    if ch == " " or ch == " ":
        glyphs[ch] = [round(adv, 2), 0, 0, 0, 0, -1]
        continue
    mask, (ox, oy) = f.getmask2(ch, anchor="ls")
    w, h = mask.size
    data = bytes(mask)
    glyphs[ch] = [round(adv, 2), w, h, ox, oy, len(blob)]
    blob += data

packed = base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
src = f"""/* Generated by tools/make_deck_font.py (Nov 14) — do not edit.
   Glyphs for drawing Stream Deck keys without a font library: Liberation Sans Bold (SIL Open Font License 1.1,
   copyright Red Hat / Liberation authors) and, for a few symbols, DejaVu Sans Bold (Bitstream Vera / DejaVu license).
   Each glyph: [advance, width, height, x offset, y offset from the baseline, byte offset] at {EM} px per em;
   coverage bytes are zlib-compressed below. */
"use strict";
module.exports = {{ EM: {EM}, ASCENT: {asc}, DESCENT: {desc}, GLYPHS: {json.dumps(glyphs, ensure_ascii=True, separators=(",", ":"))},
  DATA: "{packed}" }};
"""
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write(src)
print(f"{len(glyphs)} glyphs, {len(blob)} bytes of coverage -> {len(packed)} base64 chars; missing:",
      "".join(c for c in chars if c not in glyphs) or "none")
